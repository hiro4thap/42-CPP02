#include "Fixed.hpp"

int main( void ) {
	Fixed a;
	Fixed const b( Fixed( 5.05f ) * Fixed( 2 ) );

	std::cout << a << std::endl;
	std::cout << ++a << std::endl;
	std::cout << a << std::endl;
	std::cout << a++ << std::endl;
	std::cout << a << std::endl;

	std::cout << b << std::endl;

	std::cout << Fixed::max( a, b ) << std::endl;

	std::cout << std::endl;
	std::cout << "--- Additional Tests Comparison ---" << std::endl;
	std::cout << (a < b) << std::endl;
	std::cout << (a > b) << std::endl;
	std::cout << (a <= b) << std::endl;
	std::cout << (a >= b) << std::endl;
	std::cout << (a == b) << std::endl;
	std::cout << (a != b) << std::endl;

	std::cout << std::endl;
	std::cout << "--- Additional Tests Decrement ---" << std::endl;
	std::cout << a << std::endl;
	std::cout << --a << std::endl;
	std::cout << a << std::endl;
	std::cout << a-- << std::endl;
	std::cout << a << std::endl;

	std::cout << std::endl;
	std::cout << "--- Additional Tests Arithmetics ---" << std::endl;
	Fixed const p(15.3f);
	Fixed const q(5.1f);
	std::cout << Fixed(p + q) << std::endl;
	std::cout << Fixed(p - q) << std::endl;
	std::cout << Fixed(p / q) << std::endl;

	return 0;
}
